/**
 * Newest first, for anywhere readers browse the journal. The array itself stays
 * in the order entries were written, since each post's "Entry №" is its
 * position there and the founder's letter should remain № 01.
 */
export function journalNewestFirst() {
  return [...journal].sort((a, b) => b.publishedAt.localeCompare(a.publishedAt));
}

export function getJournalPost(slug: string) {
  return journal.find((p) => p.slug === slug);
}
